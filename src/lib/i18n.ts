export function localeTag(locale: Locale) {
  return locale === "si" ? "si-LK" : "en-GB";
}

export function formatDate(d: string, locale: Locale = "en") {
  return new Date(d).toLocaleDateString(localeTag(locale), {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}

export function formatNumber(n: number, locale: Locale = "en") {
  return n.toLocaleString(localeTag(locale));
}

export function categoryLabel(name: string, messages: Messages) {
  return messages.categories[name] ?? name;
}
